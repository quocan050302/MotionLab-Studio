class EffectRegistry:
    """Validated registry of all 40 ML-01 effects with cycle-free fallback checking & strict parameter validation."""

    def __init__(self, specs: list[EffectSpec]) -> None:
        self._by_id: dict[str, EffectSpec] = {}
        self._by_code: dict[str, EffectSpec] = {}
        for s in specs:
            if s.id in self._by_id:
                raise ValueError(f"Duplicate effect id '{s.id}'")
            if s.code in self._by_code:
                raise ValueError(f"Duplicate effect code '{s.code}'")
            self._by_id[s.id] = s
            self._by_code[s.code] = s
        self._verify_fallback_acyclic()

    def _verify_fallback_acyclic(self) -> None:
        for eid in self._by_id:
            visited: set[str] = set()
            cur: str | None = eid
            while cur is not None:
                if cur in visited:
                    raise ValueError(f"Fallback cycle detected involving effect '{cur}'")
                if cur not in self._by_id:
                    raise ValueError(f"Unknown fallback effect '{cur}' referenced from '{eid}'")
                visited.add(cur)
                cur = self._by_id[cur].fallback_id

    def get(self, effect_id: str) -> EffectSpec:
        if effect_id not in self._by_id:
            raise KeyError(f"Unknown effect_id '{effect_id}'")
        return self._by_id[effect_id]

    def get_by_code(self, code: str) -> EffectSpec:
        if code not in self._by_code:
            raise KeyError(f"Unknown effect code '{code}'")
        return self._by_code[code]

    def all_specs(self) -> list[EffectSpec]:
        return sorted(self._by_id.values(), key=lambda s: s.code)

    def core_specs(self) -> list[EffectSpec]:
        return [s for s in self.all_specs() if s.is_core]

    def ids(self) -> list[str]:
        return [s.id for s in self.all_specs()]

    def validate_params(self, effect_id: str, params: dict[str, Any]) -> dict[str, Any]:
        spec = self.get(effect_id)
        unknown = set(params.keys()) - set(spec.parameter_schema.keys())
        if unknown:
            raise ValueError(f"Unknown parameter(s) {sorted(unknown)} for effect '{effect_id}'")
        resolved: dict[str, Any] = {}
        for key, schema in spec.parameter_schema.items():
            val = params.get(key, schema["default"])
            stype = schema["type"]
            if stype == "number":
                if isinstance(val, bool) or not isinstance(val, (int, float)) or not math.isfinite(float(val)):
                    raise ValueError(f"Parameter '{key}' of '{effect_id}' must be finite number, got {val!r}")
                fval = float(val)
                if fval < schema["min"] or fval > schema["max"]:
                    raise ValueError(
                        f"Parameter '{key}'={fval} out of bounds [{schema['min']}, {schema['max']}] for '{effect_id}'"
                    )
                resolved[key] = round(fval, 5)
            elif stype == "integer":
                if isinstance(val, bool) or not isinstance(val, int):
                    raise ValueError(f"Parameter '{key}' of '{effect_id}' must be int, got {val!r}")
                if val < schema["min"] or val > schema["max"]:
                    raise ValueError(
                        f"Parameter '{key}'={val} out of bounds [{schema['min']}, {schema['max']}] for '{effect_id}'"
                    )
                resolved[key] = val
            elif stype == "enum":
                if val not in schema["choices"]:
                    raise ValueError(
                        f"Parameter '{key}'={val!r} not in allowed choices {schema['choices']} for '{effect_id}'"
                    )
                resolved[key] = val
            else:
                raise ValueError(f"Unsupported schema type '{stype}'")
        return resolved


_DEFAULT_REGISTRY: EffectRegistry | None = None


def load_effects() -> EffectRegistry:
    """Load and verify the singleton validated 40-effect registry."""
    global _DEFAULT_REGISTRY
    if _DEFAULT_REGISTRY is None:
        _DEFAULT_REGISTRY = EffectRegistry(_build_effect_specs())
    return _DEFAULT_REGISTRY
